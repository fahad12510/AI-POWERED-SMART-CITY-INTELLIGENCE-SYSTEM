import os
import json
from dotenv import load_dotenv
import analytics

load_dotenv()

def _context(data):
    return {"dashboard": analytics.dashboard_summary(data), "analytics": analytics.full_analytics(data),
            "predictions": analytics.predictions(data)}

def _groq(prompt):
    key = os.getenv("GROQ_API_KEY", "").strip()
    model = os.getenv("GROQ_MODEL", "").strip()
    if not key or not model:
        return None
    try:
        from groq import Groq
        client = Groq(api_key=key, timeout=25.0)
        response = client.chat.completions.create(
            model=model,
            messages=[{"role":"system","content":"You are a careful educational smart-city data analyst. Use only supplied facts, do not invent numbers. Give informational suggestions, not official instructions."},
                      {"role":"user","content":prompt}],
            temperature=0.3, max_tokens=900)
        return response.choices[0].message.content
    except Exception:
        return None

def _demo(data, kind="analysis"):
    d = analytics.dashboard_summary(data)
    if kind == "recommendations":
        return ("DEMO CONTENT — not generated by live AI.\\n"
                f"1. Review recurring traffic pressure around {d['highest_traffic_location']}.\\n"
                f"2. Investigate elevated sample AQI readings around {d['highest_aqi_location']}.\\n"
                "3. Continue collecting consistent readings over a longer period.\\n"
                "4. Validate these fictional sample values before any real-world decision.")
    return ("DEMO CONTENT — live Groq AI is unavailable.\\n"
            f"The dataset contains {d['locations_count']} monitored locations. "
            f"{d['highest_traffic_location']} has the highest average traffic, while "
            f"{d['highest_aqi_location']} has the highest average AQI. "
            "These are educational sample readings, not live city measurements.")

def analyze(data):
    context = _context(data)
    answer = _groq("Explain these computed smart-city results in simple language. Mention highest traffic, highest average AQI, patterns, monitoring priorities and limitations. Data: " + json.dumps(context))
    return {"mode":"live" if answer else "demo", "content":answer or _demo(data)}

def recommendations(data):
    context = _context(data)
    answer = _groq("Give 3 to 5 practical informational recommendations based only on these computed metrics. Do not give official traffic or health instructions. Data: " + json.dumps(context))
    return {"mode":"live" if answer else "demo", "content":answer or _demo(data,"recommendations")}

def ask(data, question):
    context = _context(data)
    answer = _groq("Answer the user's question using only this computed data. If unavailable, say so. Question: " + question + "\\nData: " + json.dumps(context))
    if not answer:
        return {"mode":"demo", "content":_demo(data) + "\\n\\nDemo mode cannot answer arbitrary questions with live AI. Review the dashboard metrics above."}
    return {"mode":"live", "content":answer}

def explain(data, topic):
    context = _context(data)
    answer = _groq("Explain this selected smart-city chart or metric for a beginner: " + str(topic) + ". Use only this data: " + json.dumps(context))
    return {"mode":"live" if answer else "demo", "content":answer or _demo(data)}
